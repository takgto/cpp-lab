md(r"""
### 結果 ―― 番兵は人数分いる

Infer が2人なので Read は番兵を2個流し、各 Infer は自分が受け取った1個を下流へ渡すので、
Show には**2個**届きます。**この「人数分」の管理が、番兵方式のいちばん厄介なところ**です。

| | 番兵 | `close()` |
|---|---|---|
| キューに手を入れる | 要らない | 要る |
| 順序 | **保たれる**（データと同じ列に並ぶ） | 列に並ばない |
| 人数の管理 | **人数分そろえる必要がある** | 要らない |
| 途中でやめる | **向かない**（前のデータが全部さばけるまで届かない） | **向く**（誰でもいつでも閉じられる） |
| データ型 | 「ありえない値」が必要 | 不要 |

> **通常の終了なら、どちらでもよい。「途中でやめる」が要るなら `close()` 方式。**

読んでいるプログラムがどちらを使っているかは、**キューのクラスに `close` に相当するものが
あるかどうか**を見れば分かります。
"""),

